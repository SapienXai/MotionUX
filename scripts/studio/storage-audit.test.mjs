import assert from "node:assert/strict";
import { test } from "node:test";
import { link, lstat, mkdir, mkdtemp, realpath, rename, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { auditStorage } from "./storage-audit.mjs";

test("storage audit counts logical links, allocates hardlinks once and neither follows nor changes files", async t => {
  const temp = await mkdtemp(join(await realpath(tmpdir()), "motion-storage-"));
  t.after(() => rm(temp, { recursive: true, force: true }));
  const vault = join(temp, "vault");
  const runtime = join(vault, "runtime");
  const outside = join(temp, "outside");
  await mkdir(runtime, { recursive: true });
  await mkdir(outside);
  await writeFile(join(outside, "outside.txt"), "not in the vault".repeat(4000));
  await mkdir(join(vault, "backups"));
  await writeFile(join(vault, "backups", "backup.json"), "{}");
  const source = join(runtime, "fixture.json");
  const alias = join(runtime, "fixture-copy.json");
  const target = join(vault, "redirect");
  await writeFile(source, "{synthetic fixture}");
  await link(source, alias);
  await symlink(outside, target);
  const before = await lstat(source);
  const report = await auditStorage(vault);
  assert.equal(report.status, "complete");
  assert.equal(report.usage.entries, 7);
  assert.equal(report.duplicateHardlinkAllocationsSkipped, 1);
  assert.equal(report.symlinksSkipped, 1);
  assert.equal(report.breakdown["original-runtimes-and-registry"].logicalBytes, before.size * 2);
  assert.equal(report.breakdown["protected-library-backups-and-journals"].logicalBytes, 2);
  assert.equal(report.cleanup.executed, false);
  assert.equal((await lstat(source)).mtimeMs, before.mtimeMs);
  assert.equal((await lstat(source)).ino, before.ino);
  assert.equal(JSON.stringify(report).includes(outside), false);
  await assert.rejects(auditStorage(target), /canonical/);
  await assert.rejects(auditStorage(vault, { limit: 2 }), /budget/);
  await assert.rejects(auditStorage(vault, { signal: AbortSignal.abort() }), { name: "AbortError" });
  const running = assert.rejects(auditStorage(vault));
  await rename(vault, join(temp, "vault-displaced"));
  await symlink(outside, vault);
  await running;
});
